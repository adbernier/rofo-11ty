"use strict";
const fs = require("fs");
const path = require("path");
const root = path.resolve(__dirname, "..");
const readJson = file => JSON.parse(fs.readFileSync(path.join(root, "data/internal/rofo-trust-provenance-v1", file), "utf8"));
const assert = (condition, message) => { if (!condition) throw new Error(message); };
const sources = readJson("source-registry.json").sources;
const historical = readJson("historical-claims.json").claims;
const current = readJson("current-product-claims.json").claims;
const provenance = readJson("claim-provenance.json");
const sourceIds = new Set(sources.map(source => source.id));
const claimIds = new Set([...historical, ...current].map(claim => claim.id));
assert(sources.length === 3, "Expected exactly two historical sources and one current-product source");
assert(new Set(sources.map(source => source.id)).size === sources.length, "Duplicate source ID");
for (const claim of [...historical, ...current]) for (const sourceId of claim.sourceIds) assert(sourceIds.has(sourceId), `Unknown source ${sourceId}`);
for (const claim of provenance.publicPrototypeClaims) for (const claimId of claim.claimIds) assert(claimIds.has(claimId), `Unknown claim ${claimId}`);
assert(sources.find(source => source.id.startsWith("sfgate")).publicationDate === "2008-11-05", "SFGATE date drift");
assert(sources.find(source => source.id.startsWith("inc-")).publicationDate === "2010-07-26", "Inc. date drift");
assert(sources.filter(source => source.sourceType === "THIRD_PARTY_HISTORICAL_COVERAGE").every(source => source.imageRights === "NOT_ASSUMED"), "Historical image rights must not be assumed");
assert(provenance.rejectedClaims.some(claim => claim.text.includes("2007")), "The unsupported 2007 claim must remain explicitly rejected");
console.log(`Rofo trust provenance QA passed (${historical.length} historical claims, ${sources.length} sources).`);
