import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createInterviewState,applyInterviewAnswer,selectNextQuestion,backInterview,hydrateInterviewState} from '../lib/requirements/requirement-interview-v1.mjs';
import {seedTrustedEntryContext} from '../lib/requirements/requirement-entry-context-bootstrap.mjs';
const geo={markets:{'san-francisco':[{districtId:'financial-district',name:'Financial District'}]}};
const entry={intent:'new',marketId:'san-francisco',propertyType:'office'};
let state=seedTrustedEntryContext(createInterviewState({districtGeography:geo}),entry,geo);
state.seedRequirement=structuredClone(state.requirement);
const first=selectNextQuestion(state).question;
state=applyInterviewAnswer(state,first.id,{districtIds:['financial-district'],optionIds:['financial-district']});
const second=selectNextQuestion(state).question;
console.log('questions',first.id,second.id);
state=applyInterviewAnswer(state,second.id,{optionId:'open_new'});
const restored=hydrateInterviewState(JSON.parse(JSON.stringify(state)));
const back=backInterview(restored);
assert.equal(selectNextQuestion(back).question.id,second.id);
assert.equal(back.requirement.propertyTypes[0],'office');
assert.equal(back.requirement.locationLogic.marketAnchor.marketId,'san-francisco');
assert(back.requirement.locationLogic.specificPreference.candidateDistrictIds.includes('financial-district'));
const source=fs.readFileSync(new URL('../js/requirement-prototype.js',import.meta.url),'utf8');
assert(source.includes('if (sfPilotDraftEnabled && locationBriefV2Intent === "new" && !state.interview.seedRequirement)'));
