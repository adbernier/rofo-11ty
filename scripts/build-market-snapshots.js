const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const INPUT_PATH = path.join(ROOT, "_data/raw/market-snapshots.csv");
const OUTPUT_PATH = path.join(ROOT, "_data/marketSnapshots.generated.js");

const COLUMNS = [
  "state",
  "city_slug",
  "snapshot_title",
  "average_rent",
  "average_rent_direction",
  "average_rent_label",
  "availability_rate",
  "availability_direction",
  "availability_label",
  "market_trend",
  "market_trend_direction",
  "market_trend_label",
  "notable_areas",
  "notable_areas_label",
  "summary",
  "rent_note",
  "availability_note",
  "tenant_takeaway",
];

const REQUIRED_FIELDS = ["state", "city_slug", "snapshot_title"];
const SNAPSHOT_VALUE_FIELDS = ["average_rent", "availability_rate", "market_trend", "notable_areas"];
const DIRECTION_FIELDS = ["average_rent_direction", "availability_direction", "market_trend_direction"];
const VALID_DIRECTIONS = new Set(["", "up", "down", "flat"]);

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let inQuotes = false;

  for (let index = 0; index < text.length; index += 1) {
    const char = text[index];
    const next = text[index + 1];

    if (inQuotes && char === '"' && next === '"') {
      field += '"';
      index += 1;
      continue;
    }

    if (char === '"') {
      inQuotes = !inQuotes;
      continue;
    }

    if (!inQuotes && char === ",") {
      row.push(field);
      field = "";
      continue;
    }

    if (!inQuotes && (char === "\n" || char === "\r")) {
      if (char === "\r" && next === "\n") index += 1;
      row.push(field);
      if (row.some((value) => value.trim())) rows.push(row);
      row = [];
      field = "";
      continue;
    }

    field += char;
  }

  if (field || row.length) {
    row.push(field);
    if (row.some((value) => value.trim())) rows.push(row);
  }

  return rows;
}

function slugify(value) {
  return String(value || "")
    .trim()
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function normalizeState(value) {
  return String(value || "").trim().toUpperCase();
}

function rowToObject(headers, row) {
  return headers.reduce((object, header, index) => {
    object[header] = String(row[index] || "").trim();
    return object;
  }, {});
}

function buildSnapshot(row) {
  const snapshot = {};

  for (const column of COLUMNS) {
    if (column === "state" || column === "city_slug") continue;
    const value = row[column];
    if (!value) continue;

    if (column === "notable_areas") {
      const areas = value.split("|").map((area) => area.trim()).filter(Boolean);
      if (areas.length) snapshot.notable_areas = areas;
      continue;
    }

    snapshot[column] = value;
  }

  return snapshot;
}

function validateRow(row, lineNumber, warnings) {
  for (const field of REQUIRED_FIELDS) {
    if (!row[field]) warnings.push(`Line ${lineNumber}: missing required field "${field}".`);
  }

  const valueCount = SNAPSHOT_VALUE_FIELDS.filter((field) => row[field]).length;
  if (valueCount < 2) {
    warnings.push(`Line ${lineNumber}: fewer than 2 snapshot values among ${SNAPSHOT_VALUE_FIELDS.join(", ")}.`);
  }

  for (const field of DIRECTION_FIELDS) {
    const value = String(row[field] || "").trim().toLowerCase();
    if (!VALID_DIRECTIONS.has(value)) {
      warnings.push(`Line ${lineNumber}: invalid ${field} "${row[field]}"; use up, down, flat, or blank.`);
    }
  }
}

function serializeSnapshots(snapshots) {
  return `// Generated by scripts/build-market-snapshots.js. Do not edit directly.\nmodule.exports = ${JSON.stringify(snapshots, null, 2)};\n`;
}

function main() {
  if (!fs.existsSync(INPUT_PATH)) {
    throw new Error(`Missing input CSV: ${path.relative(ROOT, INPUT_PATH)}`);
  }

  const rows = parseCsv(fs.readFileSync(INPUT_PATH, "utf8"));
  const headers = rows.shift() || [];
  const missingColumns = COLUMNS.filter((column) => !headers.includes(column));
  if (missingColumns.length) {
    throw new Error(`Missing CSV columns: ${missingColumns.join(", ")}`);
  }

  const warnings = [];
  const snapshots = {};

  rows.forEach((rawRow, index) => {
    const lineNumber = index + 2;
    const row = rowToObject(headers, rawRow);
    validateRow(row, lineNumber, warnings);

    const state = normalizeState(row.state);
    const citySlug = slugify(row.city_slug);
    if (!state || !citySlug || !row.snapshot_title) return;

    const key = `${state}/${citySlug}`;
    snapshots[key] = buildSnapshot({ ...row, state, city_slug: citySlug });
  });

  fs.writeFileSync(OUTPUT_PATH, serializeSnapshots(snapshots));

  console.log(`Wrote ${Object.keys(snapshots).length} market snapshots to ${path.relative(ROOT, OUTPUT_PATH)}.`);
  if (warnings.length) {
    console.warn(`Warnings (${warnings.length}):`);
    warnings.forEach((warning) => console.warn(`- ${warning}`));
  }
}

main();
